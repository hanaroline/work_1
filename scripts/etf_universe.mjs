/** 수집기가 도는 순서대로 평평하게 편다. */
export function universe() {
  const out = [];
  for (const [market, list] of [['US', US], ['HK', HK], ['JP', JP], ['SS', SS], ['SZ', SZ]]) {
    for (const [ticker, koName] of list) {
      out.push({
        ticker,
        market,
        symbol: ticker + EXCHANGES[market].suffix,   // 야후에 물어볼 심볼
        koName: koName || null,
        currency: EXCHANGES[market].currency,
      });
    }
  }
  return out;
}

/** 중복 티커 점검 — 목록을 손으로 고치다 보면 반드시 생긴다. */
export function duplicates() {
  const seen = new Map();
  const dups = [];
  for (const it of universe()) {
    if (seen.has(it.symbol)) dups.push(it.symbol);
    seen.set(it.symbol, true);
  }
  return dups;
}
