/**
 * 목차 쪽 — 「목차」 라는 낱말로만 찾으면 놓친다.
 *
 * 표본에서 우리프랭클린 문서의 목차 쪽에는 그 낱말이 없었다
 * (「〈투자결정시 유의사항〉〈요약정보〉 제1부. 모집 또는 매출에 관한 사항 …」).
 * 그 바람에 요약정보가 목차 쪽으로 잡혔다 — 창구가 고객 앞에서 목차를 펴게 되는
 * 값이라 통계로 덮을 수 없다.
 *
 * 그래서 낱말이 아니라 생김새로 가른다. 번호 붙은 절 제목이 한 쪽에 다섯 개 넘게
 * 늘어서 있으면 본문이 아니라 목차다. 본문 한 쪽에 서로 다른 절 제목이 다섯 개
 * 들어가는 일은 없다.
 */
const TOC_TITLE = /\d+\s*\.\s*(집합투자기구의|투자목적|투자대상|투자전략|투자위험|매입|보수|이익\s*배\s*분|운용전문인력|재무|집합투자업자)/g;

/**
 * 쪽을 「제N부」 로 여는 쪽 — 인쇄 쪽번호가 앞에 오는 것까지만 봐준다.
 *
 * 이 쪽은 구간의 첫 쪽이지 목차가 아니다. 제2부 첫 쪽에는 1~5절 제목이 표로
 * 몰려 있어 아래 개수 규칙에 걸렸고, 그 바람에 **제2부를 통째로 놓쳤다**.
 * 제2부를 못 찾으면 본문 자리가 전부 비므로 값비싼 오인이다.
 *
 * ★ 줄머리에 있을 때만 본다 ★ 아무 데나 「제1부」 가 보이면 넘기는 식으로 하면,
 * 낱말 없는 목차 쪽(「〈투자결정시 유의사항〉〈요약정보〉 제1부. 모집 또는 매출 …」)
 * 까지 본문으로 여겨 요약정보가 목차 쪽을 가리키게 된다 — 전에 우리프랭클린에서
 * 실제로 겪은 오류다.
 *
 * ★ 그런데 목차 쪽도 「제1부」 로 시작한다 ★ 이 건너뛰기가 진짜 목차 쪽까지
 * 건너뛰어 108종목이 통째로 버려졌다. 원문은 이렇다 (트러스톤 · 다올, 10/10 이 같은 꼴).
 *
 *     p.2  「2 제 1 부 모집 또는 매출에 관한 사항  1. 집합투자기구의 명칭
 *           2. 집합투자기구의 종류 및 형태  3. 모집예정금액  4. 모집의 내용 및 절차
 *           5. 인수에 관한 사항  6. 상장 및 매매에 관한 사항
 *           제 2 부 . 집합투자기구에 관한 사항  1. 집합투자기구의 명칭  2. …」
 *
 * 목차를 놓치면 제1부가 이 목차 쪽(p.2)으로 잡혀 요약정보(p.4)보다 앞서고, 앞머리
 * 차례가 어긋나 그 종목이 버려진다. 제2부도 이 쪽에서 걸렸다가 「요약정보보다 앞」
 * 이라 함께 버려져, 창구가 짚는 일곱 자리가 통째로 빈다.
 *
 * 가르는 표는 원문에 있다 — **목차는 제1부와 제2부를 한 쪽에 함께 늘어놓는다.**
 * 구간을 여는 속표지는 제 구간만 말한다. 그래서 「제N부로 쪽을 여는데 다른 부는
 * 말하지 않을 때」 만 건너뛴다.
 */
const PART_OPEN = /^\s*\d{0,4}\s*제\s*([12])\s*부/;
/** 그 쪽이 말하는 **다른** 부 — 이것이 같이 있으면 속표지가 아니라 목차다 */
const OTHER_PART = { 1: /제\s*2\s*부/, 2: /제\s*1\s*부/ };

/**
 * 절 제목이 다섯 개 넘는다는 것만으로는 목차라고 할 수 없다.
 *
 * 제2부 첫 쪽에도 1~5절(명칭·연혁·신탁계약기간·집합투자업자·운용전문인력)이
 * 표로 몰려 있어 똑같이 다섯 개를 넘긴다. 그 쪽을 목차로 여기는 바람에 본문
 * 시작을 못 잡는 문서가 남았다 — 값이 비싼 오인이다.
 *
 * 그래서 목차임을 말해 주는 표를 하나 더 요구한다. 목차는 제1부·제2부를 **함께**
 * 늘어놓거나, 제목 뒤에 점선을 깔아 쪽번호를 붙인다. 제2부 첫 쪽에는 둘 다 없다.
 */
const TOC_MARK = /제\s*1\s*부|\.{4,}|·{4,}|…{2,}/;
export function tocPages(pages) {
  const set = new Set();
  for (let i = 0; i < Math.min(pages.length, 14); i++) {
    const head = pages[i].slice(0, 120);
    if (/목\s*차/.test(head)) { set.add(i); continue; }
    const open = head.match(PART_OPEN);
    /* 제N부로 쪽을 열되 다른 부는 말하지 않으면 속표지다 — 목차가 아니다 */
    if (open && !OTHER_PART[open[1]].test(pages[i])) continue;
    if (!TOC_MARK.test(pages[i])) continue;
    if ((pages[i].match(TOC_TITLE) || []).length >= 5) set.add(i);
  }
  return set;
}

