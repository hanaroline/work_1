export const flat = (s) => String(s).replace(/\s+/g, ' ').trim();

/**
 * 이 걸림이 **절 제목**인가, 어디를 보라는 **상호참조**인가.
 *
 * 차례 조건만으로는 못 가른다. 앞쪽 상호참조를 건너뛰어도 그 다음이 또 상호참조인
 * 문서가 절반이었다 — 표본에서 눈으로 대조해 알았다.
 *
 *   ✗ p.38 「환매수수료 세부사항은 ‘제 2 부 13. 보수 및 수수료에 관한사항’ 을 참고하시기 바랍니다」
 *   ✗ p.33 「열람 방법 등 : 제 2 부 , 10. 집합투자기구의 투자위험 - 외국 집합투자기구의 …」
 *   ✓ p.21 「… 재분류할 수 있습니다 . 11. 매입 , 환매 , 전환절차 및 기준가격 적용기준 가 . 매입 (1) 매입방법」
 *   ✓ p.40 「… 의결함 13. 보수 및 수수료에 관한 사항 이 투자신탁은 운용 및 판매 등의 대가로 …」
 *
 * 가르는 표가 둘 있다.
 *   ① 앞에 「제2부」 가 붙어 있다 — 「제2부 11. 매입…」 은 그 절을 가리키는 말이지
 *      그 절 자체가 아니다. 진짜 제목 앞에는 앞 절의 끝문장이 온다.
 *   ② 뒤에 참고·참조·바랍니다·설명되어 가 곧바로 온다 — 진짜 제목 뒤에는
 *      그 절의 내용(가. · (1) · 이 투자신탁은 …)이 온다.
 *
 * 창이 좁은 것은 일부러다. 절 내용 안에도 「…를 참고하십시오」 가 나올 수 있어,
 * 제목 바로 뒤가 아니면 참조로 보지 않는다.
 */
const REF_BEFORE = /제\s*2\s*부/;
const REF_AFTER = /참\s*고|참\s*조|바랍니다|설명되어/;
export function isCrossRef(text, idx, len) {
  if (REF_BEFORE.test(text.slice(Math.max(0, idx - 30), idx))) return true;
  if (REF_AFTER.test(text.slice(idx + len, idx + len + 40))) return true;
  return false;
}

/**
 * 제2부가 시작하는 쪽을 찾는다 — 본문 시작을 정하는 자리라 값이 가장 비싸다.
 *
 * 제2부를 못 찾으면 그 종목은 본문 쪽이 전부 빈칸이고, **잘못 찾으면** 본문 시작이
 * 요약 구간으로 당겨져 창구가 엉뚱한 쪽을 편다. 그래서 다른 자리와 달리 따로 가린다.
 *
 * 문서가 이 말을 쓰는 방식이 세 가지다 (표본 원문에서 확인).
 *
 *   ① 쪽을 그 제목으로 연다        「9 제2부 집합투자기구에 관한 사항 1. 집합투자기구의 명칭 …」
 *   ② 쪽 한가운데서 시작한다        「… 펀드코드 AR640 AR556 제 2 부 집합투자기구에 관한 사항 1. …」
 *      (앞에 표가 먼저 와서 쪽 머리만 보면 놓친다 — 12/40 종목이 이 꼴이었다)
 *   ③ 다른 데를 가리키는 상호참조다  「… “제 2 부 . 집합투자기구에 관한 사항 11. 매입 , 환매 ,
 *      전환기준 ” 에서 상세하게 설명되어 있습니다」 ← 이것을 잡으면 안 된다
 *
 * ★ 「제목 뒤」 를 보면 안 된다 — 여기서 크게 헛짚었다 ★
 *
 * 처음엔 「제목 **뒤에** 1. 집합투자기구의 명칭이 이어지면 진짜」 로 가렸다.
 * 그 규칙으로 25% 를 못 찾았고, 세 번을 고쳐도 숫자가 안 움직였다. 원문을 펼쳐
 * 보니 못 찾은 10종목 중 9종목이 같은 꼴이었다.
 *
 *     p.11  「변경 ( 최용근 → 김고은 / 서한백 )  제 2 부 . 집합투자기구에 관한 사항」
 *     p.12  「- 12 -  3. 집합투자기구의 신탁계약기간 …」        ← 3절로 시작한다
 *
 * 1절·2절이 이미 지나간 것이다. **PDF 에서 뽑은 글의 순서는 눈에 보이는 순서가
 * 아니다.** 제2부 제목은 쪽 위에 큼직하게 얹힌 띠글인데 판독기가 그것을 쪽
 * 텍스트의 맨 끝에 내놓는다. 그러니 「제목 뒤」 라는 자리 자체가 성립하지 않는다.
 * 종이를 읽는 사람의 순서를 가정한 것이 틀렸다.
 *
 * 그래서 **쪽 전체**를 본다. 같은 쪽 어디에든 「1. 집합투자기구의 명칭」 이 있으면
 * 그 쪽이 제2부다 — 뽑힌 순서가 어떻든 상관없다.
 *
 * 상호참조는 그래도 걸러야 한다. 가르는 표는 **제목 바로 뒤에 붙는 절 번호**다.
 *
 *     진짜   「제2부 집합투자기구에 관한 사항 [14] 1. 집합투자기구의 명칭 …」
 *     참조   「제2부 . 집합투자기구에 관한 사항 11. 매입 , 환매 , 전환기준 ” 에서 …」
 *     참조   「제2부 . 집합투자기구에 관한 사항 중 10. 집합투자기구의 투자위험 ’ 을 …」
 *
 * 1절이 아닌 절 번호가 바로 뒤에 붙으면 그건 어디를 보라는 말이다.
 */
/* 낱말 한가운데가 벌어진 문서가 있다 — 「제 2 부 . 집 합투자기구에 관한 사항」.
   PDF 가 글자 사이를 띄워 놓은 것이라 뜻은 같다. 글자마다 공백을 허용한다.
   이만큼 긴 말이 우연히 걸릴 일은 없고, 상호참조는 그대로 뒤의 절 번호로 가린다. */
const P2_OPEN = /제\s*2\s*부[.\s]*집\s*합\s*투\s*자\s*기\s*구\s*에\s*관\s*한(\s*사\s*항)?/g;
const P2_FIRST_SECTION = /1\s*\.\s*집\s*합\s*투\s*자\s*기\s*구\s*의\s*명\s*칭/;
/* 제목 바로 뒤에 「(중) N.」 이 붙는데 그 N 이 1절(집합투자기구의 명칭)이 아니면 상호참조.
   인쇄 쪽번호가 끼어드는 것(「… 관한 사항 14 1. 집합투자기구의 명칭」)은 이 꼴이 아니다.

   ★ 「中」 도 받는다 ★ 한자로 적는 문서가 있다. 브이아이 p.8 원문 —
     「투자설명서 제2부. 집합투자기구에 관한 사항 中 11. 매입, 환매, 전환절차 …
      를 참고하시기 바랍니다」
   한글 「중」 만 알던 탓에 이 상호참조를 못 걸러 그 쪽을 제2부로 잡았다. */
const P2_POINTS_ELSEWHERE = /^\s*([중中]\s*)?\d{1,2}\s*[.)]/;
/* 참조를 뜻하는 말 — 제목이 쪽 끝에 걸린 속표지를 받을 때 앞을 살펴본다 */
const P2_REFERS = /자세한|내용은|참고|참조|설명|바랍니다|페이지|에\s*대한/;
/**
 * 그 쪽이 **제1부를 여는 쪽**인가.
 *
 * ★ 「1. 집합투자기구의 명칭」 은 제2부만의 것이 아니다 ★ 제1부의 첫 절 제목도
 * 글자 하나 다르지 않게 같다. 원문 —
 *
 *   p.9 「브이 스타국공채법인MMF 1호 9 제 1 부. 모집 또는 매출에 관한 사항
 *        1. 집합투자기구의 명칭 집합투자기구 명칭 금융투자협회 펀드코드 …」
 *
 * 그래서 제1부를 여는 쪽에 제2부 상호참조가 하나라도 있으면(이 서식은 「자세한
 * 투자대상은 제2부 … 참고하시기 바랍니다」 를 제1부 안에 늘 둔다) 그 쪽이 제2부로
 * 잡힌다. 같은 쪽에 1절이 있다는 조건이 제1부 것으로 성립해 버리기 때문이다.
 * 다음 쪽으로 확인하는 속표지 조건도 마찬가지로 제1부 첫 쪽에 걸린다.
 *
 * 전량 6차에서 버려진 30종목 가운데 28종목이 이 꼴이었다 — 제1부와 제2부가 같은
 * 쪽으로 잡히거나(제1부 9 · 제2부 9) 제2부가 제1부보다 앞섰다.
 *
 * 그러므로 제1부를 여는 쪽은 제2부가 될 수 없고, 제2부를 확인해 줄 수도 없다.
 * 제1부가 끝나고 같은 쪽에서 제2부가 시작하는 문서라면 이 종목은 빈칸이 된다 —
 * 틀린 쪽을 짚게 하느니 비운다.
 */
const P1_OPEN = /제\s*1\s*부[.\s]*모\s*집\s*(또는|,)?\s*매\s*출/;
export function findPart2(pages, toc) {
  for (let i = 0; i < pages.length; i++) {
    if (toc && toc.has(i)) continue;
    const t = pages[i];
    /* 제1부를 여는 쪽은 제2부가 아니다 — 둘의 1절 제목이 같아 구별이 안 된다
       (P1_OPEN 머리말 참고). 이 쪽의 제2부 걸림은 모두 상호참조다. */
    if (P1_OPEN.test(t)) continue;
    P2_OPEN.lastIndex = 0;
    let x;
    while ((x = P2_OPEN.exec(t))) {
      const after = t.slice(x.index + x[0].length);

      /* ③ 먼저 상호참조를 쳐 낸다 — 제목 바로 뒤에 1절이 아닌 절 번호가 붙는 것 */
      const head = after.slice(0, 40);
      if (P2_POINTS_ELSEWHERE.test(head) && !P2_FIRST_SECTION.test(head)) continue;

      /* ① 같은 쪽 어디에든 1절이 있으면 그 쪽이 제2부다.
            뽑힌 순서는 눈에 보이는 순서가 아니므로 「뒤」 를 따지지 않는다. */
      if (P2_FIRST_SECTION.test(t)) return { page: i + 1, how: x.index <= 12 ? 'first' : 'mid' };

      /* ② 1절이 다음 쪽 첫머리에 있는 문서도 있다 (제목만 놓인 속표지).
            다음 쪽이 목차면 보지 않는다 — 목차에는 어떤 제목이든 다 있다. */
      if (!(toc && toc.has(i + 1)) && !P1_OPEN.test(pages[i + 1] || '') &&
          P2_FIRST_SECTION.test((pages[i + 1] || '').slice(0, 400))) {
        return { page: i + 1, how: 'cover' };
      }

      /* ③ 제목으로 쪽이 끝나면 속표지다 — 상호참조는 문장 한가운데라 뒤에 말이 더
            붙는다. 다만 앞이 「자세한 내용은 …」 이면 쪽을 넘어가는 참조일 수 있으니
            받지 않는다. */
      if (after.trim() === '' && !P2_REFERS.test(t.slice(Math.max(0, x.index - 40), x.index))) {
        return { page: i + 1, how: 'cover' };
      }
    }
  }
  return null;
}

/**
 * pages : 쪽마다의 텍스트 배열 (flat 을 거친 것)
 * 반환   : { at, how, toc, from, bodyFrom, bodyBy }
 *   at[key]  1부터 세는 쪽 번호. 못 찾았거나 믿을 수 없으면 담지 않는다.
 *   bodyBy   본문 시작을 무엇으로 잡았나 — 'part2' | 'part1' | null(못 잡음)
 */
export function mapPages(pages) {
  const toc = tocPages(pages);
  let last = -1;
  for (const i of toc) if (i > last) last = i;
  const from = last + 1;

  const at = {}, how = {};

  /* ① 앞머리 구간 — 목차만 빼고 처음부터, 쪽 머리에서 찾는다 */
  for (const [key, zone, re] of ANCHORS) {
    if (zone !== 'first') continue;
    for (let i = 0; i < pages.length; i++) {
      if (toc.has(i)) continue;
      if (re.test(pages[i].slice(0, HEAD))) { at[key] = i + 1; how[key] = 'first'; break; }
    }
  }

  /* ①-2 제2부는 따로 가린다 — 본문 시작을 정하는 자리라 값이 가장 비싸다.
        표본에서 제2부를 못 찾은 12종목의 원문을 찍어 보니, 제목은 있는데 쪽
        **머리**에 없었다. 앞에 표가 먼저 오기 때문이다.

            p.11  … 펀드코드 AR640 AR556 AS222 제 2 부 집합투자기구에 관한 사항
            p.15  … 3. 집합투자기구의 신탁계약기간 제 2 부 . 집합투자기구에 관한 사항

        ★ 그렇다고 쪽 전체를 그냥 뒤지면 안 된다 ★ 같은 말이 상호참조로도 쓰인다.

            p.8   … “제 2 부 . 집합투자기구에 관한 사항 11. 매입 , 환매 , 전환기준 ”
                     에서 상세하게 설명되어 있습니다

        이 쪽을 제2부로 잡으면 본문 시작이 요약 구간으로 당겨져, 고치려던 오류가
        그대로 되돌아온다. 가르는 표는 **뒤에 오는 말**이다 — 진짜 구간 첫머리는
        반드시 「1. 집합투자기구의 명칭」 으로 이어지고, 상호참조는 가리키려는
        절 번호(11. 매입 / 13. 보수)로 이어진다. 그 이어짐을 함께 요구한다. */
  delete at.part2; delete how.part2;   /* ① 의 머리글 판정은 쓰지 않는다 */
  {
    const p2 = findPart2(pages, toc);
    if (p2) { at.part2 = p2.page; how.part2 = p2.how; }
    /* 요약 구간보다 앞이면 그건 제2부가 아니다 — 잡았어도 버린다 */
    if (at.part2 && at.summary && at.part2 < at.summary) { delete at.part2; delete how.part2; }
  }

  /* ② 본문이 어디서 시작하나 — **제2부뿐이다.**
        차례가 제1부 < 제2부 여야 앞머리 인식을 믿을 수 있다. 어긋나면 그 문서는
        내가 읽은 구조가 아니므로 넘겨짚지 않는다.

        ★ 제1부로 대체하지 않는다 ★ 처음엔 제2부를 못 찾으면 제1부부터 찾게
        두었다. 표본으로 재어 보니 제1부·제2부를 다 찾은 22종목 가운데 11종목에서
        투자대상·매입환매 제목이 **그 사이**(제1부 안)에 걸렸다. 제1부는 모집·매출
        구간이라 매입 방법·투자대상 이야기가 또 나온다. 대체를 두면 절반이 틀린
        쪽을 가리키므로, 제2부를 못 찾으면 본문 자리를 통째로 비운다. */
  let bodyFrom = null, bodyBy = null;
  if (at.part2 && (!at.part1 || at.part1 < at.part2)) { bodyFrom = at.part2 - 1; bodyBy = 'part2'; }

  /* ③ 본문 자리 — 제2부부터 찾되, **절 차례를 조건으로 건다.**
   *
   * ★ 첫 걸림을 그냥 쓰면 안 된다 ★ 전량 2,815종목에서 절반(1,445)이 차례가
   * 뒤집혀 있었다.
   *
   *     투자목적 p.12 · 투자대상 p.12 · 투자전략 p.15 · 투자위험 p.16
   *     매입·환매 p.12   ← 투자전략보다 앞이다
   *
   * 제2부 앞부분(2~6쪽째)에 「자세한 내용은 13. 보수 및 수수료에 관한 사항을
   * 참고」 같은 **상호참조**가 있고, 그것이 진짜 절 제목보다 먼저 걸린다.
   * 제2부를 찾을 때 애먹은 바로 그 병인데 본문 자리에는 방어가 없었다.
   * 잘못 걸린 자리는 보수 880 · 매입환매 641 · 투자전략 261 건이었다.
   *
   * 고치는 길은 문서가 이미 알려 준다 — 금융투자협회 표준 서식은 절 차례를
   * 정해 놓았다. 투자목적 → 투자대상 → 투자전략 → 투자위험 → 매입환매 →
   * 보수 → 과세. 번호 붙은 절은 번호 순서대로 인쇄되므로 쪽 번호도 이 차례대로
   * 늘어나야 한다. 그래서 각 자리는 **앞 자리보다 뒤에 있는 첫 걸림**을 고른다.
   * 상호참조는 대개 진짜 절보다 앞에 있으므로 자연히 걸러진다.
   *
   * 운용전문인력은 이 사슬에 넣지 않는다. 문서상 투자목적보다 앞(5절)이라
   * 사슬의 첫 고리가 되는데, 58% 만 잡히는 자리라 그것이 잘못 걸리면 뒤의
   * 일곱 자리가 통째로 밀린다. 보조 자리 하나를 살리려고 창구가 짚는 일곱을
   * 걸 수는 없다. 따로 찾는다.
   */
  if (bodyFrom !== null) {
    const hitsOf = (re) => {
      const g = new RegExp(re.source, 'g');
      const h = [];
      for (let i = bodyFrom; i < pages.length; i++) {
        if (toc.has(i)) continue;
        const t = pages[i];
        g.lastIndex = 0;
        let x, real = false;
        /* 한 쪽에 상호참조와 진짜 제목이 같이 있을 수 있으므로 걸림을 모두 본다 */
        while ((x = g.exec(t))) if (!isCrossRef(t, x.index, x[0].length)) { real = true; break; }
        if (real) h.push(i + 1);
      }
      return h;
    };
    const mark = (n, extra) => bodyBy + (extra ? '↓' + extra : '') + (n > 1 ? '(+' + (n - 1) + ')' : '');

    /* 사슬에 넣지 않는 본문 자리 (지금은 운용전문인력뿐) */
    for (const [key, zone, re] of ANCHORS) {
      if (zone !== 'body' || BODY_SEQ.indexOf(key) >= 0) continue;
      const h = hitsOf(re);
      if (h.length) { at[key] = h[0]; how[key] = mark(h.length, 0); }
    }

    /* 차례를 지키며 고른다 */
    let floor = 0;
    for (const key of BODY_SEQ) {
      const a = ANCHORS.find((x) => x[0] === key);
      if (!a) continue;
      const h = hitsOf(a[2]);
      const before = h.filter((p) => p < floor).length;
      const rest = h.slice(before);
      if (!rest.length) continue;          /* 앞 자리보다 뒤에 없으면 비운다 */
      at[key] = rest[0];
      how[key] = mark(rest.length, before);
      floor = rest[0];
    }
  }

  return { at, how, toc: [...toc].map((i) => i + 1), from: from + 1, bodyFrom: bodyFrom === null ? 0 : bodyFrom + 1, bodyBy };
}

/**
 * 담긴 쪽 번호가 **차례에 맞는가** 를 본다.
 *
 * 적중률은 「무언가 찾았나」 만 센다. 요약 구간을 본문으로 잘못 짚어도 적중률은
 * 100% 로 나온다 — 실제로 그렇게 2,924종목을 만들고도 못 알아봤다. 그래서 값이
 * 아니라 **차례**를 본다. 서식이 정한 차례를 거스르면 그건 다른 구간을 짚은 것이다.
 *
 * 반환 : { bad, why } — bad 가 true 면 그 종목은 담지 않는다
 */
export const BODY_SEQ = ['object', 'target', 'strategy', 'risk', 'trade', 'fee', 'tax'];
export function checkOrder(at) {
  /* 본문 자리는 모두 제2부 뒤에 있어야 한다 */
  if (at.part2) {
    for (const k of BODY_SEQ) if (at[k] && at[k] < at.part2) return { bad: true, why: k + ' 가 제2부보다 앞' };
  }
  /* 본문 자리끼리도 서식이 정한 차례를 지켜야 한다.
     ★ 이 검사가 없어서 절반이 뒤집힌 지도를 통과시켰다 ★ 「제2부보다 뒤인가」 만
     보고 자리끼리의 차례는 안 봤다. 상호참조를 진짜 절로 잘못 짚으면 제2부보다는
     뒤이면서 앞 자리보다는 앞인 값이 나오는데, 그게 정확히 그 꼴이었다. */
  let prev = 0, prevKey = '';
  for (const k of BODY_SEQ) {
    const p = at[k];
    if (!p) continue;
    if (prev && p < prev) return { bad: true, why: k + ' 가 ' + prevKey + ' 보다 앞 (p.' + p + ' < p.' + prev + ')' };
    prev = p; prevKey = k;
  }
  /* 앞머리 차례 — 요약 ≤ 제1부 < 제2부 */
  if (at.summary && at.part1 && at.summary > at.part1) return { bad: true, why: '요약정보가 제1부보다 뒤' };
  if (at.part1 && at.part2 && at.part1 >= at.part2) return { bad: true, why: '제1부가 제2부보다 뒤' };
  return { bad: false, why: '' };
}
