/** 쪽 앞부분은 「22 9. 집합투자기구의 투자전략…」 처럼 인쇄 쪽번호로 시작한다.
    그래서 제목을 줄머리에 고정하지 않고 앞부분 안에서 찾는다. */
export const HEAD = 200;

/**
 * 목차 쪽 — 「목차」 라는 낱말로만 찾으면 놓친다.
 *
 * 표본에서 우리프랭클린 문서의 목차 쪽에는 그 낱말이 없었다
 * (「〈투자결정시 유의사항〉〈요약정보〉 제1부. 모집 또는 매출에 관한 사항 …」).
 * 그 바람에 요약정보가 목차 쪽으로 잡혔다 — 창구가 고객 앞에서 목차를 펴게 되는
 * 값이라 통계로 덮을 수 없다.
 *
 * 그래서 낱말이 아니라 생김새로 가른다. 번호 붙은 절 제목이 한 쪽에 다섯 개 넘게
 * 늘어서 있으면 본문이 아니라 목차다. 본문 한 쪽에 서로 다른 절 제목이 다섯 개
 * 들어가는 일은 없다.
 */
const TOC_TITLE = /\d+\s*\.\s*(집합투자기구의|투자목적|투자대상|투자전략|투자위험|매입|보수|이익\s*배\s*분|운용전문인력|재무|집합투자업자)/g;
export function tocPages(pages) {
  const set = new Set();
  for (let i = 0; i < Math.min(pages.length, 14); i++) {
    if (/목\s*차/.test(pages[i].slice(0, 120))) { set.add(i); continue; }
    if ((pages[i].match(TOC_TITLE) || []).length >= 5) set.add(i);
  }
  return set;
}

/** PDF 쪽 텍스트를 이 규칙이 보는 꼴로 고른다 — 줄바꿈·탭을 공백 하나로 */
export const flat = (s) => String(s).replace(/\s+/g, ' ').trim();

/**
 * pages : 쪽마다의 텍스트 배열 (flat 을 거친 것)
 * 반환   : { at, how, toc, from } — at[key] 는 1부터 세는 쪽 번호, 없으면 담지 않는다
 */
export function mapPages(pages) {
  const toc = tocPages(pages);
  let last = -1;
  for (const i of toc) if (i > last) last = i;
  const from = last + 1;

  const at = {}, how = {};
  for (const [key, zone, re] of ANCHORS) {
    const hits = [];
    for (let i = zone === 'first' ? 0 : from; i < pages.length; i++) {
      if (toc.has(i)) continue;
      const t = pages[i];
      if (re.test(zone === 'body' ? t : t.slice(0, HEAD))) hits.push(i + 1);
    }
    if (!hits.length) continue;
    at[key] = hits[0];
    how[key] = zone + (hits.length > 1 ? '(+' + (hits.length - 1) + ')' : '');
  }
  return { at, how, toc: [...toc].map((i) => i + 1), from: from + 1 };
}
