/**
 * 펀드 투자설명서에서 「창구가 고객 앞에서 짚을 쪽」 을 찾는 규칙.
 *
 * 표본 조사(scripts/probe_fund_pages_sample.mjs)와 전량 생성
 * (scripts/fetch_fund_prospectus.mjs)이 **같은 규칙**을 써야 한다.
 * 두 벌로 두면 표본에서 확인한 적중률이 전량에서 그대로 나오지 않는다 —
 * 실제로 ELS 에서 그 함정을 한 번 밟았다. 그래서 규칙은 이 파일 하나뿐이다.
 *
 * ── 이 규칙이 어떻게 나왔나 ────────────────────────────────────
 * ① 핵심(요약)설명서는 투자설명서 안에 없다 (표본 6/6). 운용사가 만드는 문서에
 *    판매회사 심의필 양식이 들어 있을 리 없다. 대신 앞쪽에 「요약정보
 *    〈간이투자설명서〉」 구간이 있다 — 창구가 짚을 곳은 여기다.
 * ② 쪽 구성이 종목마다 다르다 (45~110쪽). 회차 단위로 재사용할 수 없고
 *    **종목마다** 읽어야 한다.
 * ③ 느슨한 낱말(투자목적|투자전략)은 본문에 걸려 쓸모없다. 금융투자협회 표준
 *    서식의 **번호 붙은 절 제목**으로 잡는다. 운용사가 달라도 제목은 같고,
 *    번호만 문서마다 다르므로 \d+ 로 둔다.
 * ④ 펀드 투자설명서는 ELS 교부본과 달리 절이 쪽 경계에서 시작하지 않는다.
 *    본문 중간에서 이어지므로 쪽 앞부분만 보면 대부분 놓친다 (표본 3.5/11).
 * ⑤ 과세는 제목이 「과세」 로 시작하지 않는다. 원문은
 *    「14. 이익배분 및 과세에 관한 사항」 이고 「이익 배분」 처럼 벌어지기도 한다.
 *
 * ★ 못 찾으면 비운다 ★ 틀린 쪽을 짚게 하느니 비운다. 빈칸은 직원을 문서로
 *   보내지만, 틀린 쪽은 고객 앞에서 엉뚱한 곳을 가리키게 한다.
 */

/**
 * zone 의 뜻
 *   first — 쪽을 새로 여는 앞머리 구간(요약정보·제1부·제2부). **목차보다 앞**에
 *           오는 문서가 많아 목차 뒤부터 보면 통째로 놓친다. 목차 쪽만 빼고
 *           처음부터 보되 첫 쪽을 쓴다 — 구간이 여러 쪽이어도 짚는 곳은 시작 쪽이다.
 *   body  — 번호 붙은 절 제목. **제2부가 시작하는 쪽부터** 쪽 전체에서 찾되
 *           첫 번째 쪽을 쓴다.
 *
 * ★ 본문을 어디서부터 찾는가 — 여기서 한 번 크게 틀렸다 ★
 *
 * 처음에는 「목차 다음 쪽부터」 였다. 목차만 넘기면 본문이라고 여겼는데, 실제
 * 문서의 차례는 이렇다.
 *
 *     표지 → 목차 → 요약정보〈간이투자설명서〉 → 제1부 → 제2부
 *
 * 요약정보 구간에도 같은 절 제목이 번호까지 붙어 그대로 들어 있다. 그래서 목차
 * 다음부터 찾으면 본문이 아니라 **요약 구간**이 먼저 걸린다.
 *
 * 전량 2,924종목에서 확인한 결과 — 제2부를 찾은 1,939종목 가운데 1,198종목이
 * 한 종목 안에서 요약 구간과 본문이 **섞여** 있었다. 보수는 요약 구간 6쪽,
 * 투자위험은 본문 23쪽 하는 식이다. 창구가 고객 앞에서 「보수는 6쪽입니다」 하고
 * 편 곳에는 보수 표가 아니라 요약 한 줄만 있다.
 *
 * 적중률로는 이걸 볼 수 없었다. 자리마다 99~100% 가 나왔는데, 적중률은 「무언가
 * 찾았나」 만 세지 「맞는 쪽을 찾았나」 는 세지 못한다. 그래서 이제 **차례**로
 * 검산한다 (checkOrder) — 본문 자리가 제2부보다 앞에 있으면 그건 요약 구간이다.
 *
 * 그러므로 본문 시작은 제2부다. 제2부를 못 찾으면 제1부를 쓰고, 둘 다 못 찾으면
 * **본문 자리를 통째로 비운다**. 어디부터가 본문인지 모르는 문서에서 넘겨짚으면
 * 바로 이 오류가 되돌아온다. 빈칸은 직원을 문서로 보내지만, 틀린 쪽은 고객 앞에서
 * 엉뚱한 곳을 가리키게 한다.
 */
export const ANCHORS = [
  /* 「요약정보」 라는 낱말을 안 쓰고 「〈간이투자설명서〉」 만 다는 운용사가 있다
     (신영 등). 그 구간이 곧 요약정보이므로 함께 잡는다.
     ★ 괄호를 반드시 요구한다 ★ 괄호가 없으면 유의사항 본문의 「투자설명서 또는
     간이투자설명서를 반드시 참고하시기 바랍니다」 가 걸려 엉뚱한 쪽을 가리킨다.
     실제로 그 문장은 거의 모든 문서 앞쪽에 있다. */
  ['summary', 'first', /요\s*약\s*정\s*보|[<〈[【]\s*간\s*이\s*투\s*자\s*설\s*명\s*서\s*[>〉\]】]/, '요약정보 (간이투자설명서)'],
  ['part1', 'first', /제\s*1\s*부[.\s]*모집\s*또는\s*매출/, '제1부 모집 또는 매출'],
  ['part2', 'first', /제\s*2\s*부[.\s]*집합투자기구에\s*관한/, '제2부 집합투자기구'],
  ['manager', 'body', /\d+\s*\.\s*운용전문인력에\s*관한\s*사항/, '운용전문인력'],
  ['object', 'body', /\d+\s*\.\s*(집합투자기구의\s*)?투자목적\s*(및|,)?\s*/, '투자목적'],
  ['target', 'body', /\d+\s*\.\s*(집합투자기구의\s*)?투자대상/, '투자대상'],
  ['strategy', 'body', /\d+\s*\.\s*(집합투자기구의\s*)?투자전략/, '투자전략 및 수익구조'],
  ['risk', 'body', /\d+\s*\.\s*(집합투자기구의\s*)?투자위험/, '투자위험'],
  /* 전환을 반드시 요구하던 규칙이 전량에서 76% 였다. 원문을 찍어 보니 전환 옵션이
     없는 펀드는 제목에 전환이 아예 없었다 — 「11. 집합투자증권의 매입 및 환매」.
     그래서 전환을 선택항으로 풀고 사이 기호(및·,·ㆍ)도 열어 둔다.
     ★ 「4. 수익증권의 매입•환매, 분배」 꼴(짧은 옛 서식)은 일부러 안 잡는다 ★
     그 서식은 요약 구간에도 같은 제목이 있어 어느 쪽이 창구가 짚을 곳인지
     아직 가리지 못한다. 확인하기 전까지는 비워 둔다 — 틀린 쪽보다 빈칸이 낫다. */
  ['trade', 'body', /\d+\s*\.\s*(집합투자(기구|증권)의\s*)?매\s*입\s*[,·ㆍ∙․/및\s]*환\s*매/, '매입·환매·전환절차'],
  ['fee', 'body', /\d+\s*\.\s*(집합투자기구의\s*)?보수\s*(및|,)\s*수수료/, '보수 및 수수료'],
  ['tax', 'body', /\d+\s*\.\s*이익\s*배\s*분\s*(및|,)?\s*과세/, '이익배분 및 과세'],
];

/** 쪽 앞부분은 「22 9. 집합투자기구의 투자전략…」 처럼 인쇄 쪽번호로 시작한다.
    그래서 제목을 줄머리에 고정하지 않고 앞부분 안에서 찾는다. */
export const HEAD = 200;

/**
 * 목차 쪽 — 「목차」 라는 낱말로만 찾으면 놓친다.
 *
 * 표본에서 우리프랭클린 문서의 목차 쪽에는 그 낱말이 없었다
 * (「〈투자결정시 유의사항〉〈요약정보〉 제1부. 모집 또는 매출에 관한 사항 …」).
 * 그 바람에 요약정보가 목차 쪽으로 잡혔다 — 창구가 고객 앞에서 목차를 펴게 되는
 * 값이라 통계로 덮을 수 없다.
 *
 * 그래서 낱말이 아니라 생김새로 가른다. 번호 붙은 절 제목이 한 쪽에 다섯 개 넘게
 * 늘어서 있으면 본문이 아니라 목차다. 본문 한 쪽에 서로 다른 절 제목이 다섯 개
 * 들어가는 일은 없다.
 */
const TOC_TITLE = /\d+\s*\.\s*(집합투자기구의|투자목적|투자대상|투자전략|투자위험|매입|보수|이익\s*배\s*분|운용전문인력|재무|집합투자업자)/g;

/**
 * 쪽을 「제N부」 로 여는 쪽 — 인쇄 쪽번호가 앞에 오는 것까지만 봐준다.
 *
 * 이 쪽은 구간의 첫 쪽이지 목차가 아니다. 제2부 첫 쪽에는 1~5절 제목이 표로
 * 몰려 있어 아래 개수 규칙에 걸렸고, 그 바람에 **제2부를 통째로 놓쳤다**.
 * 제2부를 못 찾으면 본문 자리가 전부 비므로 값비싼 오인이다.
 *
 * ★ 줄머리에 있을 때만 본다 ★ 아무 데나 「제1부」 가 보이면 넘기는 식으로 하면,
 * 낱말 없는 목차 쪽(「〈투자결정시 유의사항〉〈요약정보〉 제1부. 모집 또는 매출 …」)
 * 까지 본문으로 여겨 요약정보가 목차 쪽을 가리키게 된다 — 전에 우리프랭클린에서
 * 실제로 겪은 오류다.
 */
const PART_OPEN = /^\s*\d{0,4}\s*제\s*[12]\s*부/;
export function tocPages(pages) {
  const set = new Set();
  for (let i = 0; i < Math.min(pages.length, 14); i++) {
    const head = pages[i].slice(0, 120);
    if (/목\s*차/.test(head)) { set.add(i); continue; }
    if (PART_OPEN.test(head)) continue;
    if ((pages[i].match(TOC_TITLE) || []).length >= 5) set.add(i);
  }
  return set;
}

/** PDF 쪽 텍스트를 이 규칙이 보는 꼴로 고른다 — 줄바꿈·탭을 공백 하나로 */
export const flat = (s) => String(s).replace(/\s+/g, ' ').trim();

/**
 * pages : 쪽마다의 텍스트 배열 (flat 을 거친 것)
 * 반환   : { at, how, toc, from, bodyFrom, bodyBy }
 *   at[key]  1부터 세는 쪽 번호. 못 찾았거나 믿을 수 없으면 담지 않는다.
 *   bodyBy   본문 시작을 무엇으로 잡았나 — 'part2' | 'part1' | null(못 잡음)
 */
export function mapPages(pages) {
  const toc = tocPages(pages);
  let last = -1;
  for (const i of toc) if (i > last) last = i;
  const from = last + 1;

  const at = {}, how = {};

  /* ① 앞머리 구간 — 목차만 빼고 처음부터, 쪽 머리에서 찾는다 */
  for (const [key, zone, re] of ANCHORS) {
    if (zone !== 'first') continue;
    for (let i = 0; i < pages.length; i++) {
      if (toc.has(i)) continue;
      if (re.test(pages[i].slice(0, HEAD))) { at[key] = i + 1; how[key] = 'first'; break; }
    }
  }

  /* ② 본문이 어디서 시작하나 — **제2부뿐이다.**
        차례가 제1부 < 제2부 여야 앞머리 인식을 믿을 수 있다. 어긋나면 그 문서는
        내가 읽은 구조가 아니므로 넘겨짚지 않는다.

        ★ 제1부로 대체하지 않는다 ★ 처음엔 제2부를 못 찾으면 제1부부터 찾게
        두었다. 표본으로 재어 보니 제1부·제2부를 다 찾은 22종목 가운데 11종목에서
        투자대상·매입환매 제목이 **그 사이**(제1부 안)에 걸렸다. 제1부는 모집·매출
        구간이라 매입 방법·투자대상 이야기가 또 나온다. 대체를 두면 절반이 틀린
        쪽을 가리키므로, 제2부를 못 찾으면 본문 자리를 통째로 비운다. */
  let bodyFrom = null, bodyBy = null;
  if (at.part2 && (!at.part1 || at.part1 < at.part2)) { bodyFrom = at.part2 - 1; bodyBy = 'part2'; }

  /* ③ 본문 자리 — 제2부부터 쪽 전체에서 찾고 첫 쪽을 쓴다 */
  if (bodyFrom !== null) {
    for (const [key, zone, re] of ANCHORS) {
      if (zone !== 'body') continue;
      const hits = [];
      for (let i = bodyFrom; i < pages.length; i++) {
        if (toc.has(i)) continue;
        if (re.test(pages[i])) hits.push(i + 1);
      }
      if (!hits.length) continue;
      at[key] = hits[0];
      how[key] = bodyBy + (hits.length > 1 ? '(+' + (hits.length - 1) + ')' : '');
    }
  }

  return { at, how, toc: [...toc].map((i) => i + 1), from: from + 1, bodyFrom: bodyFrom === null ? 0 : bodyFrom + 1, bodyBy };
}

/**
 * 담긴 쪽 번호가 **차례에 맞는가** 를 본다.
 *
 * 적중률은 「무언가 찾았나」 만 센다. 요약 구간을 본문으로 잘못 짚어도 적중률은
 * 100% 로 나온다 — 실제로 그렇게 2,924종목을 만들고도 못 알아봤다. 그래서 값이
 * 아니라 **차례**를 본다. 서식이 정한 차례를 거스르면 그건 다른 구간을 짚은 것이다.
 *
 * 반환 : { bad, why } — bad 가 true 면 그 종목은 담지 않는다
 */
export const BODY_SEQ = ['object', 'target', 'strategy', 'risk', 'trade', 'fee', 'tax'];
export function checkOrder(at) {
  /* 본문 자리는 모두 제2부 뒤에 있어야 한다 */
  if (at.part2) {
    for (const k of BODY_SEQ) if (at[k] && at[k] < at.part2) return { bad: true, why: k + ' 가 제2부보다 앞' };
  }
  /* 앞머리 차례 — 요약 ≤ 제1부 < 제2부 */
  if (at.summary && at.part1 && at.summary > at.part1) return { bad: true, why: '요약정보가 제1부보다 뒤' };
  if (at.part1 && at.part2 && at.part1 >= at.part2) return { bad: true, why: '제1부가 제2부보다 뒤' };
  return { bad: false, why: '' };
}
