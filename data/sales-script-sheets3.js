  /**
   * 항목별 점수배열을 해당 평가표의 만점(또는 최대감점)에 맞춰 비례 조정한다.
   * 가점·배점 항목 : 배열 끝(모두 이행)이 만점 → tail 기준으로 스케일
   * 감점 항목      : 배열 앞(모두 누락)이 최대감점, 끝은 항상 0 → head 기준으로 스케일
   */
  function rescale(arr, max) {
    if (max == null || !arr.length) return arr.slice();
    var minus = max < 0;
    var anchorIdx = minus ? 0 : arr.length - 1;
    var old = arr[anchorIdx];
    if (old === max || old === 0) return arr.slice();
    var ratio = Math.abs(max) / Math.abs(old);
    var sign = minus ? -1 : 1;
    return arr.map(function (v, i) {
      if (i === anchorIdx) return max;
      if (v === 0) return 0;
      return sign * Math.round(Math.abs(v) * ratio);
    });
  }
